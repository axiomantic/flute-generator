"""OpenSCAD 3D model generator for multi-drone flutes with precision fipples and ergonomic mouthpieces."""

from pathlib import Path
from typing import Union
from .acoustics import FluteDimensions

WINDWAY_HEIGHT = 1.35       # Windway airway height (mm)
WINDWAY_WIDTH_RATIO = 0.48  # Windway width relative to bore diameter
WINDOW_LENGTH = 5.2         # Fipple sound window length (mm)
LABIUM_ANGLE = 35           # Labium splitting wedge angle (degrees)
HEAD_LENGTH = 38.0          # Head / mouthpiece height above the acoustic origin (fipple)


def generate_scad_content(dims: FluteDimensions) -> str:
    """Generate parametric OpenSCAD source code with distinct, precision fipples and ergonomic mouthpieces."""
    head_len = HEAD_LENGTH
    total_cad_length = head_len + dims.total_length
    fipple_z = total_cad_length - head_len  # Acoustic origin: Z coordinate of the labium splitting edge

    chimneys_scad = []
    holes_scad = []

    for pos in dims.hole_positions:
        # Tone hole Z = fipple splitting edge - acoustic hole distance
        abs_z = fipple_z - pos
        # Ergonomic raised chimney collar on the front (+Y) face for airtight finger sealing
        c_code = (
            f"        translate([0, bore_melody/2 + wall/2, {abs_z:.2f}]) rotate([-90, 0, 0]) "
            f"cylinder(d1={dims.hole_diameter + 6:.2f}, d2={dims.hole_diameter + 3.0:.2f}, h={dims.wall/2 + 2.5:.2f});"
        )
        chimneys_scad.append(c_code)

        # Tone hole cut through chimney, wall, and into the melody bore
        h_code = (
            f"        translate([0, 0, {abs_z:.2f}]) rotate([-90, 0, 0]) "
            f"cylinder(d={dims.hole_diameter:.2f}, h={dims.bore_melody + dims.wall * 4:.2f}, center=true);"
        )
        holes_scad.append(h_code)

    chimneys_block = "\n".join(chimneys_scad) if chimneys_scad else "        // No tone holes"
    holes_block = "\n".join(holes_scad) if holes_scad else "        // No tone holes"

    scad_template = f"""// ====================================================================
// Parametric Triple Drone Flute (Precision Fipples & Ergonomic Mouthpieces)
// Generated by flute-generator
// Root Note MIDI: {dims.root_midi}
// Total Height: {total_cad_length:.2f} mm
// Melody Bore: {dims.bore_melody:.2f} mm, Acoustic Length: {dims.length_melody:.2f} mm
// Drone 1 Bore: {dims.bore_drone1:.2f} mm, Acoustic Length: {dims.length_drone1:.2f} mm
// Drone 2 Bore: {dims.bore_drone2:.2f} mm, Acoustic Length: {dims.length_drone2:.2f} mm
// ====================================================================

$fn = 60;

// Dimensional Parameters
wall = {dims.wall:.2f};
spacing = {dims.spacing:.2f};
tol = {dims.tolerance:.2f};

bore_melody = {dims.bore_melody:.2f};
bore_drone1 = {dims.bore_drone1:.2f};
bore_drone2 = {dims.bore_drone2:.2f};

L_melody = {dims.length_melody:.2f};
L_drone1 = {dims.length_drone1:.2f};
L_drone2 = {dims.length_drone2:.2f};

head_len = {head_len:.2f};
win_len = {WINDOW_LENGTH:.2f};
w_h = {WINDWAY_HEIGHT:.2f};
total_L = {total_cad_length:.2f};
fipple_z = {fipple_z:.2f};

// Part selector for 3D printing
print_part = "assembled"; // [assembled, head, mid, foot]

// --------------------------------------------------------------------
// Body Profile Hull
// --------------------------------------------------------------------
module body_cross_section(h) {{
    hull() {{
        translate([-spacing, 0, 0]) cylinder(d=bore_drone1 + wall*2, h=h);
        translate([spacing, 0, 0]) cylinder(d=bore_drone2 + wall*2, h=h);
        translate([0, 0, h/2]) cube([spacing*1.8, bore_melody + wall*2, h], center=true);
    }}
}}

module body_with_chimneys(h) {{
    union() {{
        body_cross_section(h);
{chimneys_block}
    }}
}}

// --------------------------------------------------------------------
// Resonator Bores (start at fipple_z and run downwards to bottom base)
// --------------------------------------------------------------------
module bores() {{
    // Internal acoustic resonator chambers
    translate([-spacing, 0, fipple_z - L_drone1]) cylinder(d=bore_drone1, h=L_drone1 + 0.05);
    translate([0, 0, fipple_z - L_melody]) cylinder(d=bore_melody, h=L_melody + 0.05);
    translate([spacing, 0, fipple_z - L_drone2]) cylinder(d=bore_drone2, h=L_drone2 + 0.05);

    // Open bottom exit bores extending down through the base (Z=0)
    translate([-spacing, 0, -1]) cylinder(d=bore_drone1, h=fipple_z - L_drone1 + 1.1);
    translate([0, 0, -1]) cylinder(d=bore_melody, h=fipple_z - L_melody + 1.1);
    translate([spacing, 0, -1]) cylinder(d=bore_drone2, h=fipple_z - L_drone2 + 1.1);
}}

// --------------------------------------------------------------------
// Precision Fipple Sound Generators & Airway Windways
// --------------------------------------------------------------------
module single_fipple(offset_x, bore_d) {{
    w_w = bore_d * {WINDWAY_WIDTH_RATIO:.2f};
    y_front = bore_d / 2;
    
    translate([offset_x, 0, 0]) {{
        // 1. Windway airway channel (from top mouth entrance total_L down to sound window)
        translate([-w_w/2, y_front - w_h + 0.05, fipple_z + win_len - 0.2])
            cube([w_w, w_h, head_len - win_len + 1.2]);

        // 2. Sound window aperture (clean rectangular opening on the front face)
        translate([-w_w/2, y_front - w_h - 0.2, fipple_z])
            cube([w_w, wall + 4, win_len]);

        // 3. Labium blade splitting wedge (bevel cutting down into the bore at fipple_z)
        translate([-w_w/2, y_front + 0.1, fipple_z])
            rotate([-{LABIUM_ANGLE}, 0, 0])
                cube([w_w, wall + 3, win_len*1.6]);
    }}
}}

module all_mouthpieces_and_fipples() {{
    single_fipple(-spacing, bore_drone1);
    single_fipple(0, bore_melody);
    single_fipple(spacing, bore_drone2);

    // Subtle embouchure lip comfort bevel strictly at the very top rim (top 4mm)
    translate([0, bore_melody/2 + wall + 2, total_L])
        rotate([-30, 0, 0])
            cube([spacing*3 + 40, 10, 8], center=true);

    translate([0, -(bore_melody/2 + wall + 2), total_L])
        rotate([30, 0, 0])
            cube([spacing*3 + 40, 10, 8], center=true);
}}

// --------------------------------------------------------------------
// Complete Flute Assembly
// --------------------------------------------------------------------
module complete_flute() {{
    difference() {{
        body_with_chimneys(total_L);
        bores();
        all_mouthpieces_and_fipples();
{holes_block}
    }}
}}

// --------------------------------------------------------------------
// Print Slices & Interlocking Joints for 3D Printers
// --------------------------------------------------------------------
slice1_z = total_L * 0.35;
slice2_z = total_L * 0.70;
joint_len = 15;

module foot_slice() {{
    difference() {{
        intersection() {{
            complete_flute();
            translate([0, 0, slice1_z/2]) cube([200, 200, slice1_z], center=true);
        }}
        translate([0, 0, slice1_z - joint_len]) body_cross_section(joint_len + 1);
    }}
}}

module mid_slice() {{
    difference() {{
        union() {{
            intersection() {{
                complete_flute();
                translate([0, 0, (slice1_z + slice2_z)/2]) cube([200, 200, slice2_z - slice1_z], center=true);
            }}
            translate([0, 0, slice1_z - joint_len])
                intersection() {{
                    complete_flute();
                    body_cross_section(joint_len); 
                }}
        }}
        translate([0, 0, slice2_z - joint_len]) body_cross_section(joint_len + 1);
    }}
}}

module head_slice() {{
    union() {{
        intersection() {{
            complete_flute();
            translate([0, 0, (slice2_z + total_L)/2]) cube([200, 200, total_L - slice2_z], center=true);
        }}
        translate([0, 0, slice2_z - joint_len])
            intersection() {{
                complete_flute();
                body_cross_section(joint_len);
            }}
    }}
}}

// Output selection
if (print_part == "assembled") {{
    complete_flute();
}} else if (print_part == "head") {{
    head_slice();
}} else if (print_part == "mid") {{
    mid_slice();
}} else if (print_part == "foot") {{
    foot_slice();
}}
"""
    return scad_template


def save_scad_file(dims: FluteDimensions, output_path: Union[str, Path]) -> Path:
    """Generate and write the OpenSCAD file to output_path."""
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    content = generate_scad_content(dims)
    path.write_text(content, encoding="utf-8")
    return path
